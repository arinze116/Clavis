use near_sdk::borsh::{self, BorshDeserialize, BorshSerialize};
use near_sdk::collections::{LookupMap, Vector};
use near_sdk::json_types::U128;
use near_sdk::serde::{Deserialize, Serialize};
use near_sdk::{
    env, near_bindgen, AccountId, BorshStorageKey, Gas, NearToken, PanicOnDefault, Promise,
    PromiseOrValue, PromiseResult,
};

const DEFAULT_ROOT_ACCOUNT: &str = "clavis.testnet";
const MIN_DEPLOYMENT_BALANCE: NearToken = NearToken::from_near(6);
// Encoding the embedded payroll WASM costs substantial gas in the factory.
// Keep enough prepaid gas in this receipt before allocating the child promise.
const PROVISION_GAS: Gas = Gas::from_tgas(160);
const FACTORY_CALLBACK_GAS: Gas = Gas::from_tgas(30);
const REFUND_CALLBACK_GAS: Gas = Gas::from_tgas(5);

// The payroll WASM is generated by scripts/build-contracts.sh before the
// factory is built. Embedding it keeps deployment atomic and prevents clients
// from supplying arbitrary code to the factory.
const PAYROLL_WASM: &[u8] = include_bytes!("../res/clavis_contract.wasm");

#[derive(BorshSerialize, BorshStorageKey)]
enum StorageKey {
    Contracts,
    ContractByOwner,
    ContractByName,
    PendingDeployments,
    PendingDeploymentByOwner,
}

#[derive(BorshDeserialize, BorshSerialize, Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
#[serde(crate = "near_sdk::serde")]
pub struct ContractRecord {
    pub name: String,
    pub contract_id: AccountId,
    pub owner: AccountId,
    pub created_at: u64,
}

#[derive(BorshDeserialize, BorshSerialize)]
struct PendingDeployment {
    owner: AccountId,
    payer: AccountId,
    contract_id: AccountId,
    deposit: u128,
}

#[near_bindgen]
#[derive(BorshDeserialize, BorshSerialize, PanicOnDefault)]
pub struct Factory {
    root_account: AccountId,
    contracts: Vector<ContractRecord>,
    contract_by_owner: LookupMap<AccountId, u64>,
    contract_by_name: LookupMap<String, u64>,
    pending_deployments: LookupMap<String, PendingDeployment>,
    pending_deployment_by_owner: LookupMap<AccountId, String>,
}

#[near_bindgen]
impl Factory {
    #[init]
    pub fn new(root_account: Option<AccountId>) -> Self {
        assert!(!env::state_exists(), "Factory is already initialized");
        let root_account = root_account.unwrap_or_else(|| {
            DEFAULT_ROOT_ACCOUNT
                .parse()
                .expect("Default root account must be valid")
        });

        Self {
            root_account,
            contracts: Vector::new(StorageKey::Contracts),
            contract_by_owner: LookupMap::new(StorageKey::ContractByOwner),
            contract_by_name: LookupMap::new(StorageKey::ContractByName),
            pending_deployments: LookupMap::new(StorageKey::PendingDeployments),
            pending_deployment_by_owner: LookupMap::new(StorageKey::PendingDeploymentByOwner),
        }
    }

    /// Creates a dedicated payroll account through the parent account
    /// provisioner. NEAR only allows an account to create its direct children,
    /// so factory.clavis.testnet delegates creation of *.clavis.testnet to
    /// clavis.testnet and records the deployment after the promise succeeds.
    #[payable]
    pub fn create_payroll(
        &mut self,
        name: String,
        owner: AccountId,
        agent: AccountId,
        daily_limit: U128,
        per_payment_limit: U128,
    ) -> Promise {
        let payer = env::predecessor_account_id();
        assert_eq!(payer, owner, "The owner must submit the deployment");
        assert!(daily_limit.0 > 0, "Daily limit must be positive");
        assert!(
            per_payment_limit.0 > 0,
            "Per-payment limit must be positive"
        );
        assert!(
            per_payment_limit.0 <= daily_limit.0,
            "Per-payment limit cannot exceed daily limit"
        );

        let normalized_name = normalize_name(&name);
        assert!(
            self.contract_by_name.get(&normalized_name).is_none(),
            "Business name is already registered"
        );
        assert!(
            self.pending_deployments.get(&normalized_name).is_none(),
            "Business deployment is already pending"
        );
        assert!(
            self.contract_by_owner.get(&owner).is_none(),
            "Owner already has a Clavis contract"
        );
        assert!(
            self.pending_deployment_by_owner.get(&owner).is_none(),
            "Owner already has a Clavis deployment pending"
        );

        let deposit = env::attached_deposit();
        assert!(
            deposit >= MIN_DEPLOYMENT_BALANCE,
            "Attach at least 6 NEAR for contract storage and operating balance"
        );
        assert!(!PAYROLL_WASM.is_empty(), "Embedded payroll WASM is missing");

        let contract_id: AccountId = format!("{normalized_name}.{}", self.root_account)
            .parse()
            .expect("Validated business name must form a valid account ID");
        self.pending_deployments.insert(
            &normalized_name,
            &PendingDeployment {
                owner: owner.clone(),
                payer: payer.clone(),
                contract_id: contract_id.clone(),
                deposit: deposit.as_yoctonear(),
            },
        );
        self.pending_deployment_by_owner
            .insert(&owner, &normalized_name);

        let provision_args = near_sdk::serde_json::json!({
            "contract_id": contract_id,
            "owner": owner,
            "agent": agent,
            "daily_limit": daily_limit,
            "per_payment_limit": per_payment_limit,
            "code": near_sdk::json_types::Base64VecU8(PAYROLL_WASM.to_vec()),
        });

        Promise::new(self.root_account.clone())
            .function_call(
                "provision_payroll".to_string(),
                near_sdk::serde_json::to_vec(&provision_args)
                    .expect("Provision arguments serialize"),
                deposit,
                PROVISION_GAS,
            )
            .then(
                Promise::new(env::current_account_id()).function_call(
                    "on_payroll_created".to_string(),
                    near_sdk::serde_json::to_vec(&near_sdk::serde_json::json!({
                        "name": normalized_name,
                    }))
                    .expect("Callback arguments serialize"),
                    NearToken::from_yoctonear(0),
                    FACTORY_CALLBACK_GAS,
                ),
            )
    }

    #[private]
    pub fn on_payroll_created(&mut self, name: String) -> PromiseOrValue<AccountId> {
        let pending = self
            .pending_deployments
            .remove(&name)
            .expect("Pending deployment not found");
        self.pending_deployment_by_owner.remove(&pending.owner);
        let provisioned = match env::promise_result(0) {
            PromiseResult::Successful(bytes) => {
                near_sdk::serde_json::from_slice::<bool>(&bytes).unwrap_or(false)
            }
            PromiseResult::Failed => false,
        };

        if provisioned {
            let record = ContractRecord {
                name: name.clone(),
                contract_id: pending.contract_id.clone(),
                owner: pending.owner.clone(),
                created_at: env::block_timestamp(),
            };
            let index = self.contracts.len();
            self.contracts.push(&record);
            self.contract_by_name.insert(&name, &index);
            self.contract_by_owner.insert(&pending.owner, &index);
            env::log_str(&format!(
                "EVENT_JSON:{}",
                near_sdk::serde_json::json!({
                    "standard": "clavis_factory",
                    "version": "1.0.0",
                    "event": "payroll_created",
                    "data": [record],
                })
            ));
            return PromiseOrValue::Value(pending.contract_id);
        }

        let refund =
            Promise::new(pending.payer).transfer(NearToken::from_yoctonear(pending.deposit));
        PromiseOrValue::Promise(
            refund.then(
                Promise::new(env::current_account_id()).function_call(
                    "on_factory_refund_complete".to_string(),
                    near_sdk::serde_json::to_vec(&near_sdk::serde_json::json!({
                        "contract_id": pending.contract_id,
                    }))
                    .expect("Refund callback arguments serialize"),
                    NearToken::from_yoctonear(0),
                    REFUND_CALLBACK_GAS,
                ),
            ),
        )
    }

    #[private]
    pub fn on_factory_refund_complete(&self, contract_id: AccountId) -> AccountId {
        env::panic_str(&format!(
            "Unable to create {contract_id}; the attached deposit was refunded"
        ));
    }

    pub fn get_all_contracts(&self) -> Vec<ContractRecord> {
        self.contracts.iter().collect()
    }

    pub fn get_contract_by_owner(&self, owner: AccountId) -> Option<ContractRecord> {
        self.contract_by_owner
            .get(&owner)
            .and_then(|index| self.contracts.get(index))
    }

    pub fn is_name_available(&self, name: String) -> bool {
        let Ok(normalized) = try_normalize_name(&name) else {
            return false;
        };
        self.contract_by_name.get(&normalized).is_none()
            && self.pending_deployments.get(&normalized).is_none()
    }

    pub fn get_root_account(&self) -> AccountId {
        self.root_account.clone()
    }

    pub fn contract_version(&self) -> String {
        env!("CARGO_PKG_VERSION").to_string()
    }
}

fn normalize_name(name: &str) -> String {
    try_normalize_name(name).unwrap_or_else(|message| env::panic_str(&message))
}

fn try_normalize_name(name: &str) -> Result<String, String> {
    let normalized = name.trim().to_ascii_lowercase();
    if !(2..=32).contains(&normalized.len()) {
        return Err("Business name must be between 2 and 32 characters".to_string());
    }
    if normalized.starts_with('-') || normalized.ends_with('-') {
        return Err("Business name cannot start or end with a hyphen".to_string());
    }
    if !normalized
        .bytes()
        .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-')
    {
        return Err(
            "Business name may only use lowercase letters, numbers, and hyphens".to_string(),
        );
    }
    Ok(normalized)
}

#[cfg(test)]
mod tests {
    use super::*;
    use near_sdk::test_utils::VMContextBuilder;
    use near_sdk::testing_env;

    fn context(predecessor: &str, deposit: NearToken) -> VMContextBuilder {
        let mut builder = VMContextBuilder::new();
        builder
            .current_account_id("factory.clavis.testnet".parse().unwrap())
            .predecessor_account_id(predecessor.parse().unwrap())
            .signer_account_id(predecessor.parse().unwrap())
            .attached_deposit(deposit);
        builder
    }

    #[test]
    fn validates_business_names() {
        assert_eq!(try_normalize_name(" Acme-01 ").unwrap(), "acme-01");
        assert!(try_normalize_name("-acme").is_err());
        assert!(try_normalize_name("Acme Corp").is_err());
    }

    #[test]
    #[should_panic(expected = "Owner already has a Clavis contract")]
    fn one_contract_per_owner() {
        let owner: AccountId = "owner.testnet".parse().unwrap();
        let mut factory = Factory::new(None);
        factory.contracts.push(&ContractRecord {
            name: "existing".to_string(),
            contract_id: "existing.clavis.testnet".parse().unwrap(),
            owner: owner.clone(),
            created_at: 1,
        });
        factory.contract_by_owner.insert(&owner, &0);
        testing_env!(context("owner.testnet", NearToken::from_near(6)).build());
        factory.create_payroll(
            "newco".to_string(),
            owner,
            "agent.testnet".parse().unwrap(),
            U128(10),
            U128(5),
        );
    }

    #[test]
    #[should_panic(expected = "Owner already has a Clavis deployment pending")]
    fn one_pending_deployment_per_owner() {
        let owner: AccountId = "owner.testnet".parse().unwrap();
        testing_env!(context("owner.testnet", NearToken::from_near(6)).build());
        let mut factory = Factory::new(None);
        factory.create_payroll(
            "first".to_string(),
            owner.clone(),
            "agent.testnet".parse().unwrap(),
            U128(10),
            U128(5),
        );
        factory.create_payroll(
            "second".to_string(),
            owner,
            "agent.testnet".parse().unwrap(),
            U128(10),
            U128(5),
        );
    }
}
